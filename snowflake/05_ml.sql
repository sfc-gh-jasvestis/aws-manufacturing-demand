-- Stockout risk scoring and network demand forecast over the synthetic snapshot.
-- Predicts P(stockout for the planning item in the next 7 days) per item and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.STOCKOUT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.ITEM_AGE_YEARS,
       r.FORECAST_ERROR_PCT, r.REPLENISH_LEAD_HRS,
       AVG(r.FORECAST_ERROR_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS FORECAST_ERROR_7D,
       SUM(r.STOCKOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS STOCKOUT_30D,
       IFF(SUM(r.STOCKOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'STOCKOUT', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.ITEM_DAILY r JOIN RAW.PLANNING_ITEMS a ON a.ID = r.ENTITY_ID
-- Port congestion events are DC-wide, not item-driven, so they are excluded from training.
WHERE r.EXCEPTION_TYPE <> 'Port congestion';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.STOCKOUT_TRAIN AS
SELECT CATEGORY, RISK_TIER, ITEM_AGE_YEARS, FORECAST_ERROR_PCT, REPLENISH_LEAD_HRS, FORECAST_ERROR_7D, STOCKOUT_30D, LABEL
FROM ML.STOCKOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.STOCKOUT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, ITEM_AGE_YEARS, FORECAST_ERROR_PCT, REPLENISH_LEAD_HRS, FORECAST_ERROR_7D, STOCKOUT_30D, LABEL
FROM ML.STOCKOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.STOCKOUT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.STOCKOUT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.STOCKOUT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.STOCKOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'ITEM_AGE_YEARS', ITEM_AGE_YEARS,
           'FORECAST_ERROR_PCT', FORECAST_ERROR_PCT, 'REPLENISH_LEAD_HRS', REPLENISH_LEAD_HRS,
           'FORECAST_ERROR_7D', FORECAST_ERROR_7D, 'STOCKOUT_30D', STOCKOUT_30D)):probability:STOCKOUT::FLOAT AS P
  FROM ML.STOCKOUT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'STOCKOUT', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'STOCKOUT', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'STOCKOUT', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'STOCKOUT', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per planning item (label unknown, so excluded from features).
CREATE TABLE ML.STOCKOUT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.STOCKOUT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.STOCKOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'ITEM_AGE_YEARS', ITEM_AGE_YEARS,
           'FORECAST_ERROR_PCT', FORECAST_ERROR_PCT, 'REPLENISH_LEAD_HRS', REPLENISH_LEAD_HRS,
           'FORECAST_ERROR_7D', FORECAST_ERROR_7D, 'STOCKOUT_30D', STOCKOUT_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:STOCKOUT::FLOAT, 4) AS STOCKOUT_PROB_7D,
       CASE WHEN P:probability:STOCKOUT::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:STOCKOUT::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide demand forecast (14 days, units) from the daily series, for supply planning.
CREATE VIEW ML.DAILY_DEMAND AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(DEMAND_UNITS)::FLOAT AS DEMAND_UNITS
FROM RAW.ITEM_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.DEMAND_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_DEMAND),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'DEMAND_UNITS'
);

CREATE TABLE ML.DEMAND_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS DEMAND_UNITS,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.DEMAND_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
