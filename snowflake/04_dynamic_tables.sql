-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT item.ID AS ENTITY_ID, item.NAME AS ENTITY_NAME,
       item.REGION, item.CATEGORY, item.RISK_TIER, item.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.DEMAND_UNITS) AS DEMAND_UNITS,
       SUM(observation.DEMAND_VALUE_SGD) AS DEMAND_VALUE_SGD,
       SUM(observation.EXCEPTION_COUNT) AS EXCEPTION_COUNT,
       SUM(observation.STOCKOUT_COUNT) AS STOCKOUT_COUNT,
       SUM(observation.EXPEDITED_SHIPMENT) AS EXPEDITED_COUNT,
       SUM(observation.PLAN_REVIEW_DUE) AS PLAN_REVIEW_DUE,
       SUM(observation.PLAN_REVIEW_DONE) AS PLAN_REVIEW_DONE,
       100.0 * COUNT_IF(observation.EXCEPTION_COUNT = 0) / NULLIF(COUNT(*), 0) AS EXCEPTION_FREE_DAY_PCT,
       100.0 * SUM(observation.STOCKOUT_COUNT) / NULLIF(SUM(observation.EXCEPTION_COUNT), 0) AS EXCEPTION_STOCKOUT_PCT,
       100.0 * SUM(observation.PLAN_REVIEW_DONE) / NULLIF(SUM(observation.PLAN_REVIEW_DUE), 0) AS PLAN_REVIEW_PCT,
       AVG(observation.FORECAST_ERROR_PCT) AS AVG_FORECAST_ERROR_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.ITEM_DAILY observation
JOIN RAW.PLANNING_ITEMS item ON item.ID = observation.ENTITY_ID
GROUP BY item.ID, item.NAME, item.REGION, item.CATEGORY, item.RISK_TIER, item.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(DEMAND_UNITS) AS DEMAND_UNITS, SUM(DEMAND_VALUE_SGD) AS DEMAND_VALUE_SGD,
       SUM(EXCEPTION_COUNT) AS EXCEPTION_COUNT, SUM(STOCKOUT_COUNT) AS STOCKOUT_COUNT,
       100.0 * SUM(STOCKOUT_COUNT) / NULLIF(SUM(EXCEPTION_COUNT), 0) AS EXCEPTION_STOCKOUT_PCT
FROM RAW.ITEM_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.EXCEPTION_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EXCEPTION_TYPE, SUM(EXCEPTION_COUNT) AS EXCEPTION_COUNT,
       SUM(STOCKOUT_COUNT) AS STOCKOUT_COUNT,
       SUM(EXPEDITED_SHIPMENT) AS EXPEDITED_COUNT,
       SUM(DEMAND_VALUE_SGD) AS EXPOSED_VALUE_SGD,
       100.0 * SUM(STOCKOUT_COUNT) / NULLIF(SUM(EXCEPTION_COUNT), 0) AS EXCEPTION_STOCKOUT_PCT
FROM RAW.ITEM_DAILY
WHERE EXCEPTION_COUNT > 0
GROUP BY EXCEPTION_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(DEMAND_UNITS) AS UNITS, SUM(EXCEPTION_COUNT) AS EXCEPTIONS, COUNT(*) AS ITEM_DAYS, COUNT_IF(EXCEPTION_COUNT = 0) AS FREE_DAYS,
         SUM(STOCKOUT_COUNT) AS STOCKOUTS, SUM(EXPEDITED_SHIPMENT) AS EXPEDITES, SUM(DEMAND_VALUE_SGD) AS DEMAND_VALUE_SGD,
         SUM(PLAN_REVIEW_DUE) AS PLAN_REVIEW_DUE, SUM(PLAN_REVIEW_DONE) AS PLAN_REVIEW_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.ITEM_DAILY
), book AS (SELECT COUNT(*) AS ITEM_COUNT FROM RAW.PLANNING_ITEMS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.SUPPLIER_CONFIRMATIONS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Exception-Free Day Rate' AS TITLE,
         100.0 * FREE_DAYS / NULLIF(ITEM_DAYS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Plan Exceptions Raised', EXCEPTIONS, '' FROM observations
  UNION ALL SELECT 3, 'Stockouts', STOCKOUTS, '' FROM observations
  UNION ALL SELECT 4, 'Exception Stockout Rate', 100.0 * STOCKOUTS / NULLIF(EXCEPTIONS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Expedited Shipments', EXPEDITES, '' FROM observations
  UNION ALL SELECT 6, 'Demand Value (SGD M)', DEMAND_VALUE_SGD / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Units Demanded', UNITS, '' FROM observations
  UNION ALL SELECT 8, 'Plan Review Adherence', 100.0 * PLAN_REVIEW_DONE / NULLIF(PLAN_REVIEW_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Planning Items Monitored', ITEM_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Supplier Confirmation Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Supplier Confirmations Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.EXCEPTION_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
